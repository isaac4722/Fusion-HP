        static byte B0(uint x) { return (byte)(x & 0xFF); }
        static byte B1(uint x) { return (byte)((x >> 8) & 0xFF); }
        static byte B2(uint x) { return (byte)((x >> 16) & 0xFF); }
        static byte B3(uint x) { return (byte)((x >> 24) & 0xFF); }
        static byte _b(uint x, int n) { return (byte)((x >> (n * 8)) & 0xFF); }
        static uint ROL(uint x, int n) { n &= 31; return (x << n) | (n == 0 ? 0 : (x >> (32 - n))); }
        static uint ROR(uint x, int n) { n &= 31; return (x >> n) | (n == 0 ? 0 : (x << (32 - n))); }

        // GF(2^8) con módulo RS_MOD
        static uint PolyMult(uint a, uint b)
        {
            uint t = 0;
            while (a != 0)
            {
                if ((a & 1) != 0) t ^= b;
                b <<= 1;
                a >>= 1;
            }
            return t;
        }
        static uint GfMod(uint t, uint modulus)
        {
            uint tt;
            modulus <<= 7;
            for (int i = 0; i < 8; i++)
            {
                tt = t ^ modulus;
                if (tt < t) t = tt;
                modulus >>= 1;
            }
            return t;
        }
        static uint GfMult(uint a, uint b) { return GfMod(PolyMult(a, b), RS_MOD); }

        static uint RsMatrixMultiply(byte[] sd)
        {
            var result = new byte[4];
            for (int j = 0; j < 4; j++)
            {
                byte t = 0;
                for (int k = 0; k < 8; k++)
                    t ^= (byte)GfMult(RS[j, k], sd[k]);
                result[3 - j] = t;
            }
            return (uint)((result[0] << 24) ^ (result[1] << 16) ^ (result[2] << 8) ^ result[3]);
        }

        /// <summary>Función h con clave (k=2 para 128 bits).</summary>
        static uint H(uint X, uint[] L, int k)
        {
            byte y0 = B0(X), y1 = B1(X), y2 = B2(X), y3 = B3(X);
            switch (k)
            {
                case 4:
                    y0 = (byte)(Q1[y0] ^ B0(L[3]));
                    y1 = (byte)(Q0[y1] ^ B1(L[3]));
                    y2 = (byte)(Q0[y2] ^ B2(L[3]));
                    y3 = (byte)(Q1[y3] ^ B3(L[3]));
                    goto case 3;
                case 3:
                    y0 = (byte)(Q1[y0] ^ B0(L[2]));
                    y1 = (byte)(Q1[y1] ^ B1(L[2]));
                    y2 = (byte)(Q0[y2] ^ B2(L[2]));
                    y3 = (byte)(Q0[y3] ^ B3(L[2]));
                    goto case 2;
                case 2:
                    y0 = Q1[Q0[Q0[y0] ^ B0(L[1])] ^ B0(L[0])];
                    y1 = Q0[Q0[Q1[y1] ^ B1(L[1])] ^ B1(L[0])];
                    y2 = Q1[Q1[Q0[y2] ^ B2(L[1])] ^ B2(L[0])];
                    y3 = Q0[Q1[Q1[y3] ^ B3(L[1])] ^ B3(L[0])];
                    break;
            }
            byte z0 = (byte)(multEF[y0] ^ y1 ^ multEF[y2] ^ mult5B[y3]);
            byte z1 = (byte)(multEF[y0] ^ mult5B[y1] ^ y2 ^ multEF[y3]);
            byte z2 = (byte)(mult5B[y0] ^ multEF[y1] ^ multEF[y2] ^ y3);
            byte z3 = (byte)(y0 ^ multEF[y1] ^ mult5B[y2] ^ mult5B[y3]);
            return (uint)((z0 << 24) ^ (z1 << 16) ^ (z2 << 8) ^ z3);
        }

        public Twofish128(byte[] keyMaterial)
        {
            var M = new byte[16];
            if (keyMaterial != null)
                Array.Copy(keyMaterial, M, Math.Min(keyMaterial.Length, 16));

            // keySched con N=128 → k=2
            int k = 2;
            var Me = new uint[4];
            var Mo = new uint[4];
            // palabras little-endian del buffer
            var words = new uint[4];
            for (int i = 0; i < 4; i++)
                words[i] = (uint)(M[4 * i] | (M[4 * i + 1] << 8) | (M[4 * i + 2] << 16) | (M[4 * i + 3] << 24));
            for (int i = 0; i < k; i++)
            {
                Me[i] = words[2 * i];
                Mo[i] = words[2 * i + 1];
            }
            var Sv = new uint[4];
            var vector = new byte[8];
            for (int i = 0; i < k; i++)
            {
                for (int j = 0; j < 4; j++) vector[j] = _b(Me[i], j);
                for (int j = 0; j < 4; j++) vector[j + 4] = _b(Mo[i], j);
                Sv[k - i - 1] = RsMatrixMultiply(vector);
            }
            for (int i = 0; i < 20; i++)
            {
                uint A = H(2 * i * RHO, Me, k);
                uint B = ROL(H(2 * i * RHO + RHO, Mo, k), 8);
                K[2 * i] = A + B;
                K[2 * i + 1] = ROL(A + 2 * B, 9);
            }
            FullKey(Sv, k);
        }

        public Twofish128(string keyText)
            : this(KeyBytes(keyText)) { }

        static byte[] KeyBytes(string s)
        {
            var b = new byte[16];
            if (s == null) return b;
            for (int i = 0; i < Math.Min(s.Length, 16); i++) b[i] = (byte)s[i];
            return b;
        }

        /// <summary>Genera las QF (S-boxes completas dependientes de la clave).</summary>
        void FullKey(uint[] L, int k)
        {
            for (int g = 0; g < 4; g++) S[g] = new uint[256];
            for (int i = 0; i < 256; i++)
            {
                byte y0 = (byte)i, y1 = (byte)i, y2 = (byte)i, y3 = (byte)i;
                switch (k)
                {
                    case 4:
                        y0 = (byte)(Q1[y0] ^ B0(L[3]));
                        y1 = (byte)(Q0[y1] ^ B1(L[3]));
                        y2 = (byte)(Q0[y2] ^ B2(L[3]));
                        y3 = (byte)(Q1[y3] ^ B3(L[3]));
                        goto case 3;
                    case 3:
                        y0 = (byte)(Q1[y0] ^ B0(L[2]));
                        y1 = (byte)(Q1[y1] ^ B1(L[2]));
                        y2 = (byte)(Q0[y2] ^ B2(L[2]));
                        y3 = (byte)(Q0[y3] ^ B3(L[2]));
                        goto case 2;
                    case 2:
                        y0 = Q1[Q0[Q0[y0] ^ B0(L[1])] ^ B0(L[0])];
                        y1 = Q0[Q0[Q1[y1] ^ B1(L[1])] ^ B1(L[0])];
                        y2 = Q1[Q1[Q0[y2] ^ B2(L[1])] ^ B2(L[0])];
                        y3 = Q0[Q1[Q1[y3] ^ B3(L[1])] ^ B3(L[0])];
                        break;
                }
                S[0][i] = ((uint)multEF[y0] << 24) | ((uint)multEF[y0] << 16) | ((uint)mult5B[y0] << 8) | y0;
                S[1][i] = ((uint)y1 << 24) | ((uint)mult5B[y1] << 16) | ((uint)multEF[y1] << 8) | multEF[y1];
                S[2][i] = ((uint)multEF[y2] << 24) | ((uint)y2 << 16) | ((uint)multEF[y2] << 8) | mult5B[y2];
                S[3][i] = ((uint)mult5B[y3] << 24) | ((uint)multEF[y3] << 16) | ((uint)y3 << 8) | mult5B[y3];
            }
        }

        uint Fkh(uint X)
        {
            return S[0][B0(X)] ^ S[1][B1(X)] ^ S[2][B2(X)] ^ S[3][B3(X)];
        }

        /// <summary>Descifra un bloque de 16 bytes in situ (ECB).</summary>
        public void DecryptBlock(byte[] pt, int offset)
        {
            int o = offset;
            uint R3 = K[7] ^ (uint)(pt[o + 12] | (pt[o + 13] << 8) | (pt[o + 14] << 16) | (pt[o + 15] << 24));
            uint R2 = K[6] ^ (uint)(pt[o + 8] | (pt[o + 9] << 8) | (pt[o + 10] << 16) | (pt[o + 11] << 24));
            uint R1 = K[5] ^ (uint)(pt[o + 4] | (pt[o + 5] << 8) | (pt[o + 6] << 16) | (pt[o + 7] << 24));
            uint R0 = K[4] ^ (uint)(pt[o] | (pt[o + 1] << 8) | (pt[o + 2] << 16) | (pt[o + 3] << 24));

            for (int round = 15; round >= 0; round -= 2)
            {
                // DEC_ROUND(R0, R1, R2, R3, round)
                uint T0 = Fkh(R0);
                uint T1 = Fkh(ROL(R1, 8));
                uint nR2 = ROL(R2, 1) ^ (T0 + T1 + K[2 * round + 8]);
                uint nR3 = ROR(R3 ^ (T0 + 2 * T1 + K[2 * round + 9]), 1);
                // DEC_ROUND(R2, R3, R0, R1, round-1)
                uint U0 = Fkh(nR2);
                uint U1 = Fkh(ROL(nR3, 8));
                uint mR0 = ROL(R0, 1) ^ (U0 + U1 + K[2 * (round - 1) + 8]);
                uint mR1 = ROR(R1 ^ (U0 + 2 * U1 + K[2 * (round - 1) + 9]), 1);
                R0 = mR0; R1 = mR1; R2 = nR2; R3 = nR3;
            }

            uint o3 = R1 ^ K[3];
            uint o2 = R0 ^ K[2];
            uint o1 = R3 ^ K[1];
            uint o0 = R2 ^ K[0];
            pt[o] = (byte)o0; pt[o + 1] = (byte)(o0 >> 8); pt[o + 2] = (byte)(o0 >> 16); pt[o + 3] = (byte)(o0 >> 24);
            pt[o + 4] = (byte)o1; pt[o + 5] = (byte)(o1 >> 8); pt[o + 6] = (byte)(o1 >> 16); pt[o + 7] = (byte)(o1 >> 24);
            pt[o + 8] = (byte)o2; pt[o + 9] = (byte)(o2 >> 8); pt[o + 10] = (byte)(o2 >> 16); pt[o + 11] = (byte)(o2 >> 24);
            pt[o + 12] = (byte)o3; pt[o + 13] = (byte)(o3 >> 8); pt[o + 14] = (byte)(o3 >> 16); pt[o + 15] = (byte)(o3 >> 24);
        }

        /// <summary>Descifra un arreglo (múltiplo de 16) en ECB; devuelve copia.</summary>
        public byte[] DecryptEcb(byte[] data)
        {
            if (data == null) return null;
            var r = new byte[data.Length];
            Array.Copy(data, r, data.Length);
            for (int off = 0; off + 16 <= r.Length; off += 16)
                DecryptBlock(r, off);
            return r;
        }
